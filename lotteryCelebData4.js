  function addTo(container, list) {
    if (!container) return 0;
    var n = 0;
    if (Array.isArray(container)) {
      var have = {};
      container.forEach(function (x) { if (x && x.id) have[x.id] = 1; });
      list.forEach(function (x) {
        if (have[x.id] || container.indexOf(x) !== -1) return;
        container.push(x); n += 1;
      });
      return n;
    }
    if (typeof container === 'object') {
      list.forEach(function (x) { if (container[x.id]) return; container[x.id] = x; n += 1; });
      return n;
    }
    return 0;
  }

